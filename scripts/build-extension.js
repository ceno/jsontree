#!/usr/bin/env node
/* Copies the app into extension/vendor/ so the extension can ship it.
 *
 * The extension has to be a self-contained directory for "Load unpacked", and
 * content scripts cannot reference files outside the extension root — hence the
 * copy. index.html's body becomes a JS string because bootstrap.js needs the
 * markup synchronously, without a fetch.
 *
 * Run after changing index.html, css/style.css or js/app.js.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const vendor = path.join(root, 'extension', 'vendor');

fs.mkdirSync(vendor, { recursive: true });

const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const body = html.match(/<body[^>]*>([\s\S]*)<\/body>/i);
if (!body) {
  console.error('build-extension: no <body> found in index.html');
  process.exit(1);
}
// app.js is a content script in the extension, so drop the page's script tags.
const markup = body[1].replace(/<script[\s\S]*?<\/script>/gi, '').trim();

fs.writeFileSync(
  path.join(vendor, 'markup.js'),
  '/* Generated by scripts/build-extension.js — do not edit. */\n' +
  'window.__JSONTREE_MARKUP__ = ' + JSON.stringify(markup) + ';\n'
);

for (const file of ['js/app.js', 'css/style.css', 'favicon.svg']) {
  fs.copyFileSync(path.join(root, file), path.join(vendor, path.basename(file)));
}

console.log('Built extension/vendor/ (markup.js, app.js, style.css, favicon.svg)');
